create table if not exists public.deluxe_notifications (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 title text not null,
 body text not null,
 kind text not null default 'info',
 created_at timestamptz not null default now(),
 read_at timestamptz
);
create index if not exists deluxe_notifications_user_created_idx on public.deluxe_notifications(user_id, created_at desc);
alter table public.deluxe_notifications enable row level security;
grant select, update on public.deluxe_notifications to authenticated;
drop policy if exists deluxe_notifications_read_own on public.deluxe_notifications;
create policy deluxe_notifications_read_own on public.deluxe_notifications for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists deluxe_notifications_update_own on public.deluxe_notifications;
create policy deluxe_notifications_update_own on public.deluxe_notifications for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
