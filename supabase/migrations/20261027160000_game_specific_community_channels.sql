-- Game-specific community servers: one Fans, News, and Bugs channel per game.
create table if not exists public.game_channels (
  id uuid primary key default gen_random_uuid(),
  game_id uuid not null references public.games(id) on delete cascade,
  channel_type text not null check (channel_type in ('fans','news','bugs')),
  name text not null,
  created_at timestamptz not null default now(),
  unique (game_id, channel_type)
);
create table if not exists public.game_channel_messages (
  id bigint generated by default as identity primary key,
  channel_id uuid not null references public.game_channels(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 1500),
  created_at timestamptz not null default now()
);
alter table public.game_channels enable row level security;
alter table public.game_channel_messages enable row level security;
drop policy if exists game_channels_read_published_or_owner on public.game_channels;
create policy game_channels_read_published_or_owner on public.game_channels for select to authenticated
using (exists (select 1 from public.games g where g.id=game_id and (g.status='published' or g.creator_id=(select auth.uid()) or public.is_admin())));
drop policy if exists game_channel_messages_read_accessible on public.game_channel_messages;
create policy game_channel_messages_read_accessible on public.game_channel_messages for select to authenticated
using (exists (select 1 from public.game_channels c join public.games g on g.id=c.game_id where c.id=channel_id and (g.status='published' or g.creator_id=(select auth.uid()) or public.is_admin())));
drop policy if exists game_channel_messages_insert_allowed on public.game_channel_messages;
create policy game_channel_messages_insert_allowed on public.game_channel_messages for insert to authenticated
with check (
 sender_id=(select auth.uid()) and not public.is_user_banned() and
 exists (
   select 1 from public.game_channels c join public.games g on g.id=c.game_id
   where c.id=channel_id and g.status='published' and
    ((c.channel_type in ('fans','bugs')) or (c.channel_type='news' and (g.creator_id=(select auth.uid()) or public.is_admin())))
 )
);
create or replace function public.create_default_game_channels()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
 insert into public.game_channels(game_id,channel_type,name)
 values
  (new.id,'fans',new.title || ' Fans'),
  (new.id,'news',new.title || ' News'),
  (new.id,'bugs',new.title || ' Bugs')
 on conflict (game_id,channel_type) do update set name=excluded.name;
 return new;
end;
$$;
revoke all on function public.create_default_game_channels() from public, anon, authenticated;
drop trigger if exists games_create_default_channels on public.games;
create trigger games_create_default_channels after insert or update of title on public.games
for each row execute function public.create_default_game_channels();
insert into public.game_channels(game_id,channel_type,name)
select g.id,v.channel_type,g.title||v.suffix
from public.games g cross join (values ('fans',' Fans'),('news',' News'),('bugs',' Bugs')) as v(channel_type,suffix)
on conflict (game_id,channel_type) do update set name=excluded.name;
grant select on public.game_channels, public.game_channel_messages to authenticated;
grant insert on public.game_channel_messages to authenticated;
grant usage, select on sequence public.game_channel_messages_id_seq to authenticated;
