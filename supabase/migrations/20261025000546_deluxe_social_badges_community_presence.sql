
create table if not exists public.deluxe_badges (
 id uuid primary key default gen_random_uuid(),
 game_id uuid not null references public.games(id) on delete cascade,
 creator_id uuid not null references auth.users(id) on delete cascade,
 name text not null check (char_length(name) between 1 and 50),
 image_url text not null,
 description text not null default '',
 requirement_seconds integer not null default 60 check (requirement_seconds >= 0),
 condition_type text not null default 'time_played' check (condition_type in ('time_played','text_on_screen','color_on_screen','image_on_screen')),
 condition_value text not null default '',
 created_at timestamptz not null default now()
);
create index if not exists deluxe_badges_game_idx on public.deluxe_badges(game_id,created_at desc);
create table if not exists public.user_badges (
 user_id uuid not null references auth.users(id) on delete cascade,
 badge_id uuid not null references public.deluxe_badges(id) on delete cascade,
 earned_at timestamptz not null default now(),
 primary key(user_id,badge_id)
);
alter table public.deluxe_badges enable row level security;
alter table public.user_badges enable row level security;
grant select,insert,update,delete on public.deluxe_badges to authenticated;
grant select,insert on public.user_badges to authenticated;
create policy deluxe_badges_read_all on public.deluxe_badges for select to authenticated using (true);
create policy deluxe_badges_create_own on public.deluxe_badges for insert to authenticated with check (creator_id=(select auth.uid()) and exists(select 1 from public.games g where g.id=game_id and g.creator_id=(select auth.uid())));
create policy deluxe_badges_update_own on public.deluxe_badges for update to authenticated using (creator_id=(select auth.uid())) with check (creator_id=(select auth.uid()));
create policy deluxe_badges_delete_own on public.deluxe_badges for delete to authenticated using (creator_id=(select auth.uid()));
create policy user_badges_read_own on public.user_badges for select to authenticated using (user_id=(select auth.uid()));
create policy user_badges_award_self on public.user_badges for insert to authenticated with check (user_id=(select auth.uid()) and exists(select 1 from public.deluxe_badges b where b.id=badge_id and b.condition_type='time_played'));
create table if not exists public.friend_requests (
 id uuid primary key default gen_random_uuid(),
 sender_id uuid not null references auth.users(id) on delete cascade,
 recipient_id uuid not null references auth.users(id) on delete cascade,
 status text not null default 'pending' check(status in ('pending','accepted','rejected')),
 created_at timestamptz not null default now(),
 unique(sender_id,recipient_id), check(sender_id<>recipient_id)
);
create table if not exists public.friendships (
 user_id uuid not null references auth.users(id) on delete cascade,
 friend_id uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now(),
 primary key(user_id,friend_id), check(user_id<>friend_id)
);
create table if not exists public.friend_messages (
 id bigint generated by default as identity primary key,
 sender_id uuid not null references auth.users(id) on delete cascade,
 recipient_id uuid not null references auth.users(id) on delete cascade,
 content text not null check(char_length(content) between 1 and 1000),
 created_at timestamptz not null default now(), read_at timestamptz,
 check(sender_id<>recipient_id)
);
create index if not exists friend_messages_pair_idx on public.friend_messages(sender_id,recipient_id,created_at desc);
alter table public.friend_requests enable row level security;
alter table public.friendships enable row level security;
alter table public.friend_messages enable row level security;
grant select,insert,update,delete on public.friend_requests to authenticated;
grant select,insert,delete on public.friendships to authenticated;
grant select,insert,update on public.friend_messages to authenticated;
create policy friend_requests_read_involved on public.friend_requests for select to authenticated using(sender_id=(select auth.uid()) or recipient_id=(select auth.uid()));
create policy friend_requests_send_self on public.friend_requests for insert to authenticated with check(sender_id=(select auth.uid()));
create policy friend_requests_respond on public.friend_requests for update to authenticated using(recipient_id=(select auth.uid())) with check(recipient_id=(select auth.uid()));
create policy friendships_read_own on public.friendships for select to authenticated using(user_id=(select auth.uid()));
create policy friendships_add_own on public.friendships for insert to authenticated with check(user_id=(select auth.uid()) and exists(select 1 from public.friend_requests r where r.status='accepted' and ((r.sender_id=(select auth.uid()) and r.recipient_id=friend_id) or (r.recipient_id=(select auth.uid()) and r.sender_id=friend_id))));
create policy friendships_remove_own on public.friendships for delete to authenticated using(user_id=(select auth.uid()));
create policy friend_messages_read_involved on public.friend_messages for select to authenticated using(sender_id=(select auth.uid()) or recipient_id=(select auth.uid()));
create policy friend_messages_send_to_friend on public.friend_messages for insert to authenticated with check(sender_id=(select auth.uid()) and exists(select 1 from public.friendships f where f.user_id=(select auth.uid()) and f.friend_id=recipient_id));
create policy friend_messages_mark_read on public.friend_messages for update to authenticated using(recipient_id=(select auth.uid())) with check(recipient_id=(select auth.uid()));
create table if not exists public.community_messages (
 id bigint generated by default as identity primary key,
 channel text not null check(channel in ('news','admins','general','bugs')),
 sender_id uuid not null references auth.users(id) on delete cascade,
 content text not null check(char_length(content) between 1 and 1500),
 created_at timestamptz not null default now()
);
alter table public.community_messages enable row level security;
grant select,insert on public.community_messages to authenticated;
create policy community_read_allowed on public.community_messages for select to authenticated using (
 channel in ('general','bugs','news')
 or exists(select 1 from public.user_roles ur where ur.user_id=(select auth.uid()) and ur.role='admin')
 or (channel='admins' and exists(select 1 from public.friendships f join public.user_roles ur on ur.user_id=f.friend_id where f.user_id=(select auth.uid()) and ur.role='admin')
));
create policy community_post_general_bugs on public.community_messages for insert to authenticated with check(sender_id=(select auth.uid()) and channel in ('general','bugs'));
create policy community_post_news_admin on public.community_messages for insert to authenticated with check(sender_id=(select auth.uid()) and channel='news' and exists(select 1 from public.user_roles ur where ur.user_id=(select auth.uid()) and ur.role='admin'));
create policy community_post_admins_admin on public.community_messages for insert to authenticated with check(sender_id=(select auth.uid()) and channel='admins' and exists(select 1 from public.user_roles ur where ur.user_id=(select auth.uid()) and ur.role='admin'));
create table if not exists public.deluxe_groups (
 id uuid primary key default gen_random_uuid(),
 name text not null check(char_length(name) between 1 and 60),
 owner_id uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
create table if not exists public.deluxe_group_members (
 group_id uuid not null references public.deluxe_groups(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 joined_at timestamptz not null default now(), primary key(group_id,user_id)
);
create table if not exists public.deluxe_group_messages (
 id bigint generated by default as identity primary key,
 group_id uuid not null references public.deluxe_groups(id) on delete cascade,
 sender_id uuid not null references auth.users(id) on delete cascade,
 content text not null check(char_length(content) between 1 and 1000),
 created_at timestamptz not null default now()
);
alter table public.deluxe_groups enable row level security;
alter table public.deluxe_group_members enable row level security;
alter table public.deluxe_group_messages enable row level security;
grant select,insert,update,delete on public.deluxe_groups to authenticated;
grant select,insert,delete on public.deluxe_group_members to authenticated;
grant select,insert on public.deluxe_group_messages to authenticated;
create policy groups_read_members on public.deluxe_groups for select to authenticated using(exists(select 1 from public.deluxe_group_members m where m.group_id=id and m.user_id=(select auth.uid())));
create policy groups_create_owner on public.deluxe_groups for insert to authenticated with check(owner_id=(select auth.uid()));
create policy groups_update_owner on public.deluxe_groups for update to authenticated using(owner_id=(select auth.uid())) with check(owner_id=(select auth.uid()));
create policy groups_delete_owner on public.deluxe_groups for delete to authenticated using(owner_id=(select auth.uid()));
create policy group_members_read_peers on public.deluxe_group_members for select to authenticated using(exists(select 1 from public.deluxe_group_members mine where mine.group_id=deluxe_group_members.group_id and mine.user_id=(select auth.uid())));
create policy group_members_add_self_or_owner on public.deluxe_group_members for insert to authenticated with check(user_id=(select auth.uid()) or exists(select 1 from public.deluxe_groups g where g.id=group_id and g.owner_id=(select auth.uid())));
create policy group_members_remove_self_or_owner on public.deluxe_group_members for delete to authenticated using(user_id=(select auth.uid()) or exists(select 1 from public.deluxe_groups g where g.id=group_id and g.owner_id=(select auth.uid())));
create policy group_messages_read_members on public.deluxe_group_messages for select to authenticated using(exists(select 1 from public.deluxe_group_members m where m.group_id=deluxe_group_messages.group_id and m.user_id=(select auth.uid())));
create policy group_messages_send_members on public.deluxe_group_messages for insert to authenticated with check(sender_id=(select auth.uid()) and exists(select 1 from public.deluxe_group_members m where m.group_id=deluxe_group_messages.group_id and m.user_id=(select auth.uid())));
create table if not exists public.user_presence (
 user_id uuid primary key references auth.users(id) on delete cascade,
 online boolean not null default false,
 current_game_id uuid references public.games(id) on delete set null,
 updated_at timestamptz not null default now()
);
alter table public.user_presence enable row level security;
grant select,insert,update on public.user_presence to authenticated;
